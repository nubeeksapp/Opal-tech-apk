package com.example.ads

import android.app.Activity
import android.content.Context
import android.util.Log
import java.io.File
import com.google.android.gms.ads.AdError
import com.google.android.gms.ads.AdRequest
import com.google.android.gms.ads.FullScreenContentCallback
import com.google.android.gms.ads.LoadAdError
import com.google.android.gms.ads.MobileAds
import com.google.android.gms.ads.RequestConfiguration
import com.google.android.gms.ads.interstitial.InterstitialAd
import com.google.android.gms.ads.interstitial.InterstitialAdLoadCallback
import com.google.android.gms.ads.rewarded.RewardedAd
import com.google.android.gms.ads.rewarded.RewardedAdLoadCallback

object AdManager {
    private const val TAG = "AdManager"

    private var isInitialized = false
    private var interstitialAd: InterstitialAd? = null
    private var isInterstitialLoading = false
    private var rewardedAd: RewardedAd? = null
    private var isRewardedLoading = false

    private var lastInterstitialShownTime = 0L
    private const val INTERSTITIAL_COOLDOWN_MS = 45_000L // 45 seconds cooldown to prevent spam

    /**
     * Initializes Google Mobile Ads SDK once per app lifecycle.
     */
    fun initialize(context: Context) {
        if (isInitialized) return
        try {
            cleanCorruptedVariationsSeed(context)

            val config = RequestConfiguration.Builder()
                .setTestDeviceIds(listOf(AdRequest.DEVICE_ID_EMULATOR))
                .build()
            MobileAds.setRequestConfiguration(config)

            MobileAds.initialize(context.applicationContext) { initializationStatus ->
                Log.d(TAG, "AdMob MobileAds initialized: $initializationStatus")
                isInitialized = true
                loadInterstitialAd(context.applicationContext)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error initializing MobileAds", e)
        }
    }

    /**
     * Cleans up stale or corrupted 0-byte variation seed files generated by Chromium/WebView.
     */
    private fun cleanCorruptedVariationsSeed(context: Context) {
        try {
            val dataDir = File(context.applicationInfo.dataDir)
            val webViewDir = File(dataDir, "app_webview")
            if (webViewDir.exists() && webViewDir.isDirectory) {
                webViewDir.listFiles()?.forEach { file ->
                    if (file.name.contains("variation", ignoreCase = true)) {
                        try {
                            file.delete()
                        } catch (_: Exception) {}
                    }
                }
            }
        } catch (_: Exception) {}
    }

    /**
     * Preloads an Interstitial Ad using the user-provided exact ad unit ID.
     */
    fun loadInterstitialAd(context: Context) {
        if (interstitialAd != null || isInterstitialLoading) return
        isInterstitialLoading = true

        val adRequest = AdRequest.Builder().build()
        InterstitialAd.load(
            context,
            AdConfig.INTERSTITIAL_AD_UNIT_ID,
            adRequest,
            object : InterstitialAdLoadCallback() {
                override fun onAdLoaded(ad: InterstitialAd) {
                    Log.d(TAG, "Interstitial ad loaded successfully.")
                    interstitialAd = ad
                    isInterstitialLoading = false
                }

                override fun onAdFailedToLoad(loadAdError: LoadAdError) {
                    Log.w(TAG, "Interstitial ad failed to load: ${loadAdError.message}")
                    interstitialAd = null
                    isInterstitialLoading = false
                }
            }
        )
    }

    /**
     * Displays an Interstitial Ad if available and not within the cooldown period.
     */
    fun showInterstitialAd(activity: Activity, onAdDismissed: () -> Unit = {}) {
        val currentTime = System.currentTimeMillis()
        val ad = interstitialAd

        if (activity.isFinishing || activity.isDestroyed) {
            onAdDismissed()
            return
        }

        if (ad != null && (currentTime - lastInterstitialShownTime >= INTERSTITIAL_COOLDOWN_MS)) {
            ad.fullScreenContentCallback = object : FullScreenContentCallback() {
                override fun onAdDismissedFullScreenContent() {
                    Log.d(TAG, "Interstitial ad dismissed.")
                    interstitialAd = null
                    lastInterstitialShownTime = System.currentTimeMillis()
                    loadInterstitialAd(activity.applicationContext)
                    onAdDismissed()
                }

                override fun onAdFailedToShowFullScreenContent(adError: AdError) {
                    Log.w(TAG, "Interstitial ad failed to show: ${adError.message}")
                    interstitialAd = null
                    loadInterstitialAd(activity.applicationContext)
                    onAdDismissed()
                }

                override fun onAdShowedFullScreenContent() {
                    Log.d(TAG, "Interstitial ad showed full screen.")
                }
            }
            try {
                ad.show(activity)
            } catch (e: Exception) {
                Log.w(TAG, "Exception showing interstitial ad: ${e.message}")
                interstitialAd = null
                onAdDismissed()
            }
        } else {
            // Not ready or within cooldown; proceed directly without blocking user flow
            if (ad == null && !isInterstitialLoading) {
                loadInterstitialAd(activity.applicationContext)
            }
            onAdDismissed()
        }
    }

    /**
     * Preloads a Rewarded Ad using the user-provided exact ad unit ID.
     */
    fun loadRewardedAd(context: Context) {
        if (rewardedAd != null || isRewardedLoading) return
        isRewardedLoading = true

        val adRequest = AdRequest.Builder().build()
        RewardedAd.load(
            context,
            AdConfig.REWARDED_AD_UNIT_ID,
            adRequest,
            object : RewardedAdLoadCallback() {
                override fun onAdLoaded(ad: RewardedAd) {
                    Log.d(TAG, "Rewarded ad loaded successfully.")
                    rewardedAd = ad
                    isRewardedLoading = false
                }

                override fun onAdFailedToLoad(loadAdError: LoadAdError) {
                    Log.w(TAG, "Rewarded ad failed to load: ${loadAdError.message}")
                    rewardedAd = null
                    isRewardedLoading = false
                }
            }
        )
    }

    /**
     * Returns true if a rewarded ad is loaded and ready to be shown.
     */
    fun isRewardedAdReady(): Boolean = rewardedAd != null

    /**
     * Displays a Rewarded Ad and invokes [onUserEarnedReward] when user completes watching.
     */
    fun showRewardedAd(
        activity: Activity,
        onUserEarnedReward: (Int, String) -> Unit,
        onAdClosed: () -> Unit = {},
        onAdFailed: (String) -> Unit = {}
    ) {
        if (activity.isFinishing || activity.isDestroyed) {
            onAdFailed("Screen is no longer active.")
            return
        }

        val ad = rewardedAd
        if (ad != null) {
            ad.fullScreenContentCallback = object : FullScreenContentCallback() {
                override fun onAdDismissedFullScreenContent() {
                    Log.d(TAG, "Rewarded ad dismissed.")
                    rewardedAd = null
                    loadRewardedAd(activity.applicationContext)
                    onAdClosed()
                }

                override fun onAdFailedToShowFullScreenContent(adError: AdError) {
                    Log.w(TAG, "Rewarded ad failed to show: ${adError.message}")
                    rewardedAd = null
                    loadRewardedAd(activity.applicationContext)
                    onAdFailed(adError.message)
                }

                override fun onAdShowedFullScreenContent() {
                    Log.d(TAG, "Rewarded ad showed.")
                }
            }

            try {
                ad.show(activity) { rewardItem ->
                    Log.d(TAG, "User earned reward: ${rewardItem.amount} ${rewardItem.type}")
                    onUserEarnedReward(rewardItem.amount, rewardItem.type)
                }
            } catch (e: Exception) {
                Log.w(TAG, "Exception showing rewarded ad: ${e.message}")
                rewardedAd = null
                onAdFailed("Could not show ad: ${e.message}")
            }
        } else {
            loadRewardedAd(activity.applicationContext)
            onAdFailed("Ad is loading, please try again in a moment.")
        }
    }
}
